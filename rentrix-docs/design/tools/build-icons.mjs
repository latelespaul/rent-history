// Builds mockups/assets/icons.js from icons/*.svg so the static mockups can
// inline the icons (inline SVG inherits currentColor; <img> would not).
// Usage: node rentrix-docs/design/tools/build-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'icons');
const icons = {};
for (const file of readdirSync(iconDir).sort()) {
  if (!file.endsWith('.svg') || file === 'rentrix-mark.svg') continue;
  const svg = readFileSync(join(iconDir, file), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').trim();
  icons[file.replace(/\.svg$/, '')] = inner;
}

const out = `// GENERATED by tools/build-icons.mjs from icons/*.svg. Do not edit by hand.
window.RX_ICONS = ${JSON.stringify(icons, null, 2)};
(function () {
  function render() {
    document.querySelectorAll('i[data-icon]:not(.icon)').forEach(function (el) {
      var name = el.getAttribute('data-icon');
      var body = window.RX_ICONS[name];
      if (!body) { el.textContent = '?'; el.title = 'missing icon: ' + name; return; }
      el.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" ' +
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + body + '</svg>';
      el.classList.add('icon');
    });
  }
  window.RX_renderIcons = render;
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', render);
  else render();
})();
`;
writeFileSync(join(root, 'mockups', 'assets', 'icons.js'), out);
console.log(`wrote ${Object.keys(icons).length} icons`);
