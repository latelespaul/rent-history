#!/usr/bin/env node
// Copies the design system from rentrix-docs/design into the web app:
//   tokens.css     -> src/styles/tokens.css           (verbatim, with a "generated" header)
//   icons/icons.js -> src/components/ui/icon-paths.gen.ts (path data)
//                     src/components/ui/icons.gen.ts      (one React component per icon)
// The design folder is the source of truth (DESIGN.md §4, §5); the copies exist because the
// web image builds from rentrix-web/ alone. `src/test/design-sync.test.ts` fails when they drift.
// Usage: npm run sync:design
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import path from "node:path"

const web = path.resolve(import.meta.dirname, "..")
const design = path.resolve(web, "../rentrix-docs/design")

export const TOKENS_HEADER =
  "/* Generated by scripts/sync-design.mjs from rentrix-docs/design/tokens.css. Do not edit. */\n"

const GENERATED =
  "// Generated by scripts/sync-design.mjs from rentrix-docs/design/icons/icons.js. Do not edit."

const pascal = (name) => name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase()) + "Icon"

export function iconPathsModule(icons) {
  return [
    GENERATED,
    "",
    "/** Path data of the Rentrix icon set: 24 × 24 grid, stroke only (DESIGN.md §5). */",
    "export const ICON_PATHS = {",
    ...Object.entries(icons).map(
      ([name, paths]) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`,
    ),
    "} as const satisfies Record<string, readonly string[]>",
    "",
    "export type IconName = keyof typeof ICON_PATHS",
    "",
  ].join("\n")
}

export function iconsModule(icons) {
  return [
    GENERATED,
    'import { createIcon } from "./icon"',
    "",
    ...Object.keys(icons).map(
      (name) => `export const ${pascal(name)} = createIcon(${JSON.stringify(name)})`,
    ),
    "",
  ].join("\n")
}

function main() {
  const tokens = readFileSync(path.join(design, "tokens.css"), "utf8")
  writeFileSync(path.join(web, "src/styles/tokens.css"), TOKENS_HEADER + tokens)

  const { ICONS } = createRequire(import.meta.url)(path.join(design, "icons/icons.js"))
  writeFileSync(path.join(web, "src/components/ui/icon-paths.gen.ts"), iconPathsModule(ICONS))
  writeFileSync(path.join(web, "src/components/ui/icons.gen.ts"), iconsModule(ICONS))
  console.log(`synced tokens.css and ${Object.keys(ICONS).length} icons`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) main()
